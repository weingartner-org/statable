export type Schluessel = keyof typeof de;
export const texte: Record<'de' | 'en', Record<Schluessel, string>> = { de, en };

/** Text in der Sprache holen und {Platzhalter} ersetzen. Unbekannte Sprache: Englisch bei „en-…“, sonst Deutsch. */
export function t(sprache: string, schluessel: Schluessel | string, werte: Record<string, string | number> = {}): string {
  const s: 'de' | 'en' = sprache === 'en' || sprache.startsWith('en-') ? 'en' : 'de';
  const roh = (texte[s] as Record<string, string>)[schluessel] ?? (texte.de as Record<string, string>)[schluessel] ?? schluessel;
  return roh.replace(/\{(\w+)\}/g, (m, k: string) => (k in werte ? String(werte[k]) : m));
}
