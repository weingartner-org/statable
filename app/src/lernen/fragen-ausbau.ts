/**
 * Üben: drei Lehreinheiten der Stufe A1 (Ausbau weltweit, 13.11.2026), je 3 Fragen, 9 Fragen. Grundlage sind die Hilfe-Artikel
 * `eh-verfahren`, `eh-guetekriterien-quali`, `eh-ki-offenlegen` (`hilfe/artikel-ausbau-lehre.ts`, `Hilfe:<id>`).
 * Gefragt wird nach Regeln und Zuordnungen, nie nach „der richtigen Deutung“. Alle Beispiele sind erfunden.
 * Formregeln wie `fragen-feinstruktur.ts`: vier Antworten, genau eine richtig, gleich gebaut, gleiches Klammerwort in einer Frage,
 * keine absoluten Wörter, jede falsche Antwort eine echte Fehlvorstellung, Lösungsplätze verteilt.
 */
import { P } from '../i18n/laufzeit';
import type { Antwort, Frage } from './fragen';

type Paar = ReturnType<typeof P>;
type A = [Paar, Paar];

const a = (t: Paar, w: Paar, richtig?: true): Antwort => ({ text: t, warum: w, ...(richtig ? { richtig } : {}) });

function fr(id: string, artikel: string, stamm: Paar, platz: number, richtig: A, falsch: [A, A, A]): Frage {
  const antworten: Antwort[] = falsch.map(f => a(f[0], f[1]));
  antworten.splice(platz, 0, a(richtig[0], richtig[1], true));
  return { id, thema: 'erheben', stamm, antworten, hilfe: [artikel], belege: [`Hilfe:${artikel}`] };
}

